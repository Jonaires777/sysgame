"""Portas (interfaces) da camada de aplicação — arquitetura hexagonal.

O serviço de jogo (GameService) só conhece estas interfaces. Quem as implementa são os
adaptadores: o Matrix (adapters/matrix_bot.py) e a persistência em JSON (adapters/json_store.py).
Nos testes, implementações falsas em memória tomam o lugar deles.
"""
from __future__ import annotations

from typing import Protocol

from ..domain.engine import Game


class GameRepository(Protocol):
    """Porta de saída: onde as partidas ficam guardadas."""

    def get(self, game_id: str) -> Game | None: ...
    def add(self, game: Game) -> None: ...
    def all(self) -> list[Game]: ...
    def next_number(self) -> int: ...
    def save(self) -> None: ...
    # idempotência: eventos já processados (o transporte pode reentregar)
    def seen(self, event_id: str) -> bool: ...
    def mark(self, event_id: str) -> None: ...


class GameNotifier(Protocol):
    """Porta de saída: como o resultado das jogadas chega aos jogadores."""

    async def create_game_room(self, name: str, owner: str) -> str:
        """Cria a sala da partida e devolve o id (que vira o game_id)."""
        ...

    async def publish_state(self, game: Game) -> None: ...
    async def publish_lobby(self, games: list[Game]) -> None: ...
    async def send_hand(self, game: Game, user: str, as_text: bool = False) -> None: ...
    async def send_result(self, room_id: str, event_id: str, sender: str, ok: bool,
                          seq: int | None, reason: str | None = None) -> None: ...
    async def announce(self, room_id: str, text: str) -> None: ...
    async def show_table(self, game: Game, full: bool = False) -> None: ...
